@Composable
fun Dialog(paddingValues: PaddingValues){

    var openAlertDialog by remember { mutableStateOf(false) }

    Column(modifier = Modifier.padding(paddingValues)) {
        Button(onClick = { openAlertDialog = true }, modifier = Modifier
            .padding(20.dp)
            .fillMaxWidth()) {
            Text(text = "Show Dialog")
        }
    }



    if(openAlertDialog){
        AlertDialogExample(
            onDismissRequest = { openAlertDialog = false },
            onConfirmation = { /*TODO*/ },
            dialogTitle = "Example Dialog",
            dialogText = "Hello there!",
            icon = Icons.Default.Notifications
        )
    }


}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun AlertDialogExample(
    onDismissRequest: () -> Unit,
    onConfirmation: () -> Unit,
    dialogTitle: String,
    dialogText: String,
    icon: ImageVector,
) {
    AlertDialog(
        icon = {
            Icon(icon, contentDescription = "Example Icon")
        },
        title = {
            Text(text = dialogTitle)
        },
        text = {
            Text(text = dialogText)
        },
        onDismissRequest = {
            onDismissRequest()
        },
        confirmButton = {
            TextButton(
                onClick = {
                    onConfirmation()
                }
            ) {
                Text("Confirm")
            }
        },
        dismissButton = {
            TextButton(
                onClick = {
                    onDismissRequest()
                }
            ) {
                Text("Dismiss")
            }
        }
    )


}

